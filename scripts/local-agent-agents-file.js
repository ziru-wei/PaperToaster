import path from "node:path";
import { randomUUID } from "node:crypto";
import { rename, unlink, writeFile } from "node:fs/promises";
import { hashText } from "./local-agent-session-store.js";
import { loadPaperReadingSkillMarkdown } from "./paper-reading-skill.js";

const AGENTS_FILENAME = "AGENTS.md";

// Codex reads AGENTS.md from its working directory on every invocation
// (verified against the installed codex-cli), so the skill text and the
// user's configured systemPrompt live here instead of being reinjected into
// the prompt on every turn. Writes are skipped when the content is unchanged
// and serialized so concurrent /ask calls never race on the same file.
let lastWrittenKey = "";
let writeChain = Promise.resolve();

export async function ensureAgentsMarkdown({ agentWorkdir, systemPrompt }) {
  const skillMarkdown = await loadPaperReadingSkillMarkdown();
  const content = buildAgentsMarkdown(skillMarkdown, systemPrompt);
  const key = `${agentWorkdir}\0${hashText(content)}`;
  if (key === lastWrittenKey) {
    return;
  }

  writeChain = writeChain.then(() => writeAgentsFile(agentWorkdir, content, key));
  await writeChain;
}

async function writeAgentsFile(agentWorkdir, content, key) {
  if (key === lastWrittenKey) {
    return;
  }

  const filename = path.join(agentWorkdir, AGENTS_FILENAME);
  const temp = path.join(agentWorkdir, `.tmp-agents-${randomUUID()}`);
  try {
    await writeFile(temp, content, { encoding: "utf8", mode: 0o600 });
    await rename(temp, filename);
    lastWrittenKey = key;
  } catch (error) {
    await unlink(temp).catch(() => {});
    throw error;
  }
}

function buildAgentsMarkdown(skillMarkdown, systemPrompt) {
  const trimmedSystemPrompt = String(systemPrompt || "").trim();
  return [
    "# Paper Toaster local agent instructions",
    "Generated by scripts/local-agent-server.js. Do not edit by hand; it is overwritten before the next request.",
    "",
    skillMarkdown,
    ...(trimmedSystemPrompt
      ? [
        "",
        "Additional answer instructions (from the user's Options settings; this section always reflects the current value):",
        trimmedSystemPrompt
      ]
      : [])
  ].join("\n").trim() + "\n";
}
